"""Writes app/src/main/res/values-<lang>/strings.xml for the wizard from <lang>.py, checked against the English list.

The wizard alone is translated (Ian, 14 Oct 2026); wizard_en.json lists the strings it uses. Run:
    python tools/wizard/gen.py es pt-BR fr de ja hi
After changing an English wizard string, update wizard_en.json and every <lang>.py, then rerun.
"""
import json, re, sys, importlib.util, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'res')
FOLDER = {'es': 'values-es', 'pt-BR': 'values-pt-rBR', 'fr': 'values-fr', 'de': 'values-de', 'ja': 'values-ja', 'hi': 'values-hi'}
PLURAL_FORMS = {'ja': ['other'], 'hi': ['one', 'other'], 'es': ['one', 'many', 'other'], 'pt-BR': ['one', 'many', 'other'],
                'fr': ['one', 'many', 'other'], 'de': ['one', 'other']}

def esc(t):
    t = t.replace("\\'", "'")
    t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace("'", "\\'").replace('"', '\\"')
    if t.startswith('@') or t.startswith('?'): t = '\\' + t
    return t

def placeholders(t):
    # The set, not the count: a language may name the same value more often than English does.
    return sorted(set(re.findall(r'%(?:\d+\$)?,?[sd]', t)))

def main(lang):
    en = {e['key']: e for e in json.load(open(os.path.join(HERE, 'wizard_en.json'), encoding='utf-8'))}
    spec = importlib.util.spec_from_file_location('t', os.path.join(HERE, lang.replace('-', '_') + '.py'))
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    T = mod.T
    missing = sorted(set(en) - set(T)); extra = sorted(set(T) - set(en))
    problems = []
    if missing: problems.append(f'missing: {missing}')
    if extra: problems.append(f'extra: {extra}')
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- The setup wizard only, in this language (Ian, 14 Oct 2026). Generated by tools/wizard/gen.py',
             '     from tools/wizard/<lang>.py; every other string in the app has no translation and stays English. -->',
             '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation">']
    for key in sorted(T):
        if key not in en: continue
        src = en[key]; tr = T[key]
        if src['type'] == 'string':
            if placeholders(src['en']) != placeholders(tr): problems.append(f'{key}: placeholders {placeholders(src["en"])} vs {placeholders(tr)}')
            lines.append(f'    <string name="{key}">{esc(tr)}</string>')
        else:
            ref = src['en']['other']
            lines.append(f'    <plurals name="{key}">')
            forms = dict(tr)
            if 'many' in PLURAL_FORMS[lang] and 'many' not in forms: forms['many'] = forms['other']
            for q in PLURAL_FORMS[lang]:
                text = forms.get(q) or forms['other']
                if placeholders(text) != placeholders(ref): problems.append(f'{key}/{q}: placeholders')
                lines.append(f'        <item quantity="{q}">{esc(text)}</item>')
            lines.append('    </plurals>')
    lines.append('</resources>')
    out = os.path.join(RES, FOLDER[lang]); os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(lang, len(T), 'strings;', 'PROBLEMS: ' + '; '.join(problems) if problems else 'no problems')

if __name__ == '__main__':
    for l in sys.argv[1:]: main(l)
